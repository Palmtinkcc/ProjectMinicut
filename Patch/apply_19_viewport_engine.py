                                        '    """One opened video file. Reads forward when the next frame is close, seeks otherwise."""\n'
                                        '    def __init__(self, cap):\n'
                                        '        self.cap = cap; self.pos = -10; self.raw = None; self.n = int(cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0)\n'
