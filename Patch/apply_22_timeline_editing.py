"""
MiniCut update patch 22: TIMELINE EDITING
=========================================
Install AFTER apply_22_timeline_editing.py.

Bugs fixed
  * Trimming a clip can no longer push it over its neighbour on the same track. The trimmed edge now stops at the
    neighbour, or, when the two clips touch, ROLLS it (see below).
  * Compound clips had no sound in the preview. The compound's own volume was ignored, and a compound inside another
    compound was silent. Now the volume of every compound a clip sits in (constant or animated) is applied, at any depth.
    Compound clips also show a waveform on the timeline, like other clips.

New features
  * Roll edit: drag the border between two clips that touch. One clip gets longer while the other gets shorter by the same
    amount, so there is never a gap or an overlap. It stops where either clip runs out of its own footage.
  * Group edit with trimming: trimming the left edge of a grouped clip moves the rest of the group with it (it used to only
    follow when the clip was dragged).
  * Remove gaps (like the main track in CapCut): right-click a track header, a clip, or an empty part of a track and
    choose "Remove gaps in this track" or "Remove gaps in all tracks". The first clip of a track stays in place; the others
    move left to follow the clip before them. Locked tracks are skipped. One undo step.
  * Quick volume: drag the volume line drawn on a clip up or down to set its volume (0 to 200 %), without opening the
    inspector. Clips with volume keyframes are left alone (edit those in the Keyframes tab).
  * Settings -> General -> Waveform height: makes the waves drawn on audio and video clips taller (1x to 8x, default 3x).

New file: minicut/workspace/timeline_ops.py
Changed files: minicut/workspace/timeline.py, minicut/workspace/actions.py, minicut/shared/core.py,
minicut/shared/dialogs.py (originals are backed up first)

    python apply_22_timeline_editing.py            install the update
    python apply_22_timeline_editing.py --check    only show what would change
    python apply_22_timeline_editing.py --revert   undo the last install
    python apply_22_timeline_editing.py --force    install even if you edited one of these files yourself
"""

