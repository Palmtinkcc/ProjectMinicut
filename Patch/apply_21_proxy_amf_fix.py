                                        'class AudioStore:\n'
                                        '    """Decoded audio of every file. The decoded sound is kept in a file on disk and read through a memory map, so an '
                                        'hour\n'
                                        '    of audio does not take RAM, and the next start does not decode it again."""\n'
                                        '    def __init__(self): self.data = {}; self.peaks = {}; self.files = {}; self.lock = threading.Lock()\n'
                                        '    @staticmethod\n'
                                        '    def _cache_file(path):\n'
                                        '        import hashlib\n'
                                        '        st = os.stat(path)\n'
                                        '        key = hashlib.sha1(("%s|%d|%d|%d" % (os.path.abspath(path), st.st_size, int(st.st_mtime), '
                                        'SR)).encode("utf-8")).hexdigest()[:24]\n'
                                        '        d = os.path.join(APP_DIR, "audiocache"); os.makedirs(d, exist_ok=True)\n'
                                        '        return os.path.join(d, key + ".pcm")\n'
                                        '    def _cleanup(self, keep):\n'
                                        '        """Keep the audio cache under its budget (Settings): the least recently used files go first, files in use '
                                        'stay."""\n'
                                        '        d = os.path.join(APP_DIR, "audiocache"); budget = float(CFG.get("audio_cache_gb", 8)) * 1e9\n'
                                        '        try: items = [(os.path.getmtime(os.path.join(d, f)), os.path.getsize(os.path.join(d, f)), os.path.join(d, f)) '
                                        'for f in os.listdir(d) if f.endswith(".pcm")]\n'
                                        '        except OSError: return\n'
                                        '        total = sum(s for _, s, _ in items); inuse = set(self.files.values()) | {keep}\n'
                                        '        for _, size, p in sorted(items):\n'
                                        '            if total <= budget: break\n'
                                        '            if p in inuse: continue\n'
                                        '            try: os.remove(p); total -= size\n'
                                        '            except OSError: pass\n'
                                        '    def load(self, path):\n'
                                        '        with self.lock:\n'
                                        '            if path in self.data: return self.data[path]\n'
                                        '            arr = None\n'
                                        '            try:\n'
                                        '                f = self._cache_file(path)\n'
                                        '                if not (os.path.exists(f) and os.path.getsize(f) >= 4):\n'
                                        '                    tmp = f + ".part"\n'
                                        '                    with open(tmp, "wb") as out:\n'
                                        '                        r = subprocess.run([FFMPEG, "-v", "error", "-i", path, "-vn", "-f", "s16le", "-ac", "2", '
                                        '"-ar", str(SR), "-"],\n'
                                        '                                           stdout=out, stderr=subprocess.DEVNULL, creationflags=NOWIN)\n'
                                        '                    if r.returncode == 0 and os.path.getsize(tmp) >= 4: os.replace(tmp, f)\n'
                                        '                    else:\n'
                                        '                        try: os.remove(tmp)\n'
                                        '                        except OSError: pass\n'
                                        '                if os.path.exists(f) and os.path.getsize(f) >= 4:\n'
                                        '                    arr = np.memmap(f, dtype=np.int16, mode="r", shape=(os.path.getsize(f) // 4, 2))\n'
                                        '                    try: os.utime(f)\n'
                                        '                    except OSError: pass\n'
                                        '                    self.files[path] = f; self._cleanup(f)\n'
                                        '            except Exception as ex: print("audio load:", ex)\n'
                                        '            self.data[path] = arr\n'
                                        '            if arr is not None:\n'
                                        '                hop = SR // 100; n = len(arr) // hop; pk = np.empty(n, np.float32)\n'
                                        '                for s in range(0, n, 6000):                 # one minute at a time: no big temporary arrays\n'
                                        '                    e = min(n, s + 6000); blk = np.asarray(arr[s * hop:e * hop]).astype(np.int32)\n'
                                        '                    pk[s:e] = np.abs(blk).max(axis=1).reshape(e - s, hop).max(axis=1) / 32768.0\n'
                                        '                self.peaks[path] = pk\n'
                                        '            else: self.peaks[path] = np.zeros(0, np.float32)\n'
                                        '            return arr\n'
